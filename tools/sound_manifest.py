#!/usr/bin/env python3
"""Write sounds.js, the list of recorded samples in sounds/ that replace the game's synthesized ones.

Name each file after the bank sound it replaces (the keys of BANK in src/game.ts), with an optional
take number so a sound can have several recordings to pick from at random:

    sounds/pistol-1.ogg  sounds/pistol-2.ogg  sounds/boom.mp3  sounds/shatter-1.ogg

then run:

    python3 tools/sound_manifest.py
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXTS = {'.ogg', '.mp3', '.wav', '.m4a'}

def bank_names():
    src = (ROOT / 'src' / 'game.ts').read_text(encoding='utf-8')
    body = src[src.index('const BANK:any={'):src.index('const SBK=new Map();')]
    return set(re.findall(r'^\s+(\w+):\(\)=>', body, re.M)) | set(re.findall(r'^BANK\.(\w+)=', body, re.M))

def main():
    names, files = bank_names(), {}
    for f in sorted((ROOT / 'sounds').glob('*')):
        if f.suffix.lower() not in EXTS:
            continue
        name = re.sub(r'-\d+$', '', f.stem)
        if name not in names:
            print(f'skipped {f.name}: no bank sound called "{name}"')
            continue
        files.setdefault(name, []).append(f'sounds/{f.name}')
    js = ('// Generated by tools/sound_manifest.py; do not edit by hand.\n'
          'window.SOUND_FILES=' + json.dumps(files, indent=1) + ';\n')
    (ROOT / 'sounds.js').write_text(js, encoding='utf-8')
    print(f'sounds.js -> {sum(map(len, files.values()))} files for {len(files)} sounds: {", ".join(files) or "none"}')

if __name__ == '__main__':
    main()
